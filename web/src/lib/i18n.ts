const STORAGE_KEY = "relay_lang";

function readLang(): Lang {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    return v === "en" ? "en" : "de";
  } catch {
    return "de";
  }
}

export const lang = writable<Lang>(readLang());

export function setLang(l: Lang): void {
  lang.set(l);
  try {
    localStorage.setItem(STORAGE_KEY, l);
  } catch {
    // localStorage unavailable (e.g. sandboxed iframe) — keep in-memory only.
  }
}

/** Reactive translate store — use as `{$t("key")}` in templates. */
export const t = derived(lang, ($lang) => (key: string, params?: Record<string, string | number>): string => {
  let s = translations[$lang][key] ?? translations.de[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
});

/** Non-reactive translate helper for non-component contexts. */
export function translate(key: string, params?: Record<string, string | number>): string {
  let s = translations[get(lang)][key] ?? translations.de[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

const BACKEND_ERROR_MAP: Array<[RegExp, string]> = [
  [/(x-relay-key fehlt oder ungültig|key fehlt|invalid key)/i, "error.keyMissing"],
  [/(ungültige empfänger|invalid recipient|parse_to)/i, "error.invalidRecipient"],
  [/(imap|smtp).*(login|authentifizierung|authenticat|verweigert|nicht gefunden|verbindung|connection|failed)/i, "error.imapSmtpConnect"],
  [/(verbindung|connection).*(fehlgeschlagen|failed|nicht erreichbar|timeout|zeitüberschreitung)/i, "error.connection"],
];

/**
 * Maps the most common backend-generated error messages onto a localized,
 * user-friendly text (plus the raw detail). Unrecognized messages pass through.
 */
export function localizeError(msg: string): string {
  if (!msg) return msg;
  for (const [re, key] of BACKEND_ERROR_MAP) {
    if (re.test(msg)) {
      const head = translate(key);
      return msg.trim().length > 0 ? `${head} (${msg.trim()})` : head;
    }
  }
  return msg;
}
