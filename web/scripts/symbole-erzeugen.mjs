// HB-SYMBOL — writes src/lib/symbole.ts from the CI icon set.
//
// The icons live in the copy of the CI stand, web/ci/marke/icons/ui/
// (aimighty-ci, marke/icons/ui/). A new icon goes into the CI set first,
// through its generator, then arrives here with a new stand (CI ABGLEICH R2,
// RL-Z1). Relay draws nothing directly from Lucide or Heroicons.
//
//   node scripts/symbole-erzeugen.mjs            # writes src/lib/symbole.ts
//   node scripts/symbole-erzeugen.mjs --pruefen  # exit 1 if it is out of date
//
// After Rocket's and Insilo's scripts/symbole-erzeugen.mjs.

import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const QUELLE = join(web, "ci", "marke", "icons", "ui");
const ZIEL = join(web, "src", "lib", "symbole.ts");

function innen(svg) {
  const m = svg.match(/<svg\b[^>]*>([\s\S]*)<\/svg>/);
  if (!m) throw new Error("kein <svg>");
  return m[1].trim();
}

const namen = readdirSync(QUELLE)
  .filter((n) => n.endsWith(".svg"))
  .map((n) => n.slice(0, -4))
  .sort();

const zeilen = namen.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(innen(readFileSync(join(QUELLE, `${n}.svg`), "utf8")))},`);

const inhalt = `// HB-SYMBOL — generated by scripts/symbole-erzeugen.mjs from web/ci/marke/icons/ui/, do not edit.
// The icons come from the CI set (aimighty-ci, marke/icons/ui/), Lucide 1.31.0, ISC.

export const SYMBOLE = {
${zeilen.join("\n")}
} as const;

export type SymbolName = keyof typeof SYMBOLE;

/** CI R2: 16 · 20 · 24, and 40 in empty states. */
export type Symbolgroesse = 16 | 20 | 24 | 40;
`;

if (process.argv.includes("--pruefen")) {
  const ist = existsSync(ZIEL) ? readFileSync(ZIEL, "utf8") : "";
  if (ist !== inhalt) {
    console.error("src/lib/symbole.ts weicht von web/ci/marke/icons/ui/ ab — node scripts/symbole-erzeugen.mjs");
    process.exit(1);
  }
  console.log(`${namen.length} Zeichen — gleich`);
} else {
  writeFileSync(ZIEL, inhalt);
  console.log(`src/lib/symbole.ts: ${namen.length} Zeichen`);
}
